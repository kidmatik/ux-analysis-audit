import { chromium } from "playwright-core";
const OUT = "/tmp/claude-0/e2e";
const BASE = "http://localhost:3000";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome", args: ["--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
const t0 = Date.now();
const log = (...a) => console.log(((Date.now() - t0) / 1000).toFixed(1) + "s", ...a);

await page.goto(BASE);
await page.screenshot({ path: `${OUT}/01-landing.png`, fullPage: true });
await page.click("text=Start Product Audit");
await page.waitForURL("**/signup");
await page.screenshot({ path: `${OUT}/02-signup.png` });
const email = `test${Date.now()}@example.com`;
await page.fill("input[name=name]", "Test Founder");
await page.fill("input[name=email]", email);
await page.fill("input[name=password]", "password123");
await page.click("button[type=submit]");
await page.waitForURL("**/audits/new");
log("signed up");
await page.fill("input[placeholder='Acme Analytics']", "Acme Insights");
await page.fill("input[placeholder='https://acme.com']", "http://localhost:8090/index.html");
await page.selectOption("select >> nth=0", "saas_app");
await page.screenshot({ path: `${OUT}/03-wizard-1.png` });
await page.click("text=Continue");
await page.screenshot({ path: `${OUT}/04-wizard-2.png` });
await page.click("text=Continue");
await page.screenshot({ path: `${OUT}/05-wizard-3.png` });
await page.click("text=Start Audit");
await page.waitForURL("**/processing");
await page.waitForTimeout(2500);
await page.screenshot({ path: `${OUT}/06-processing.png` });
log("processing");
await page.waitForURL(/\/audits\/[^/]+$/, { timeout: 180000 });
log("report ready", page.url());
await page.waitForLoadState("networkidle");
await page.screenshot({ path: `${OUT}/07-report-free.png`, fullPage: true });
const reportUrl = page.url();

// second scan should require Pro
await page.goto(`${BASE}/audits/new`);
log("second scan ->", page.url());
await page.goto(`${BASE}/dashboard`);
await page.screenshot({ path: `${OUT}/08-dashboard.png` });
await page.goto(`${BASE}/upgrade`);
await page.click("text=Go Pro, $39/month");
await page.waitForURL("**/dashboard?upgraded=1");
log("upgraded");
await page.goto(reportUrl);
await page.waitForLoadState("networkidle");
await page.screenshot({ path: `${OUT}/09-report-pro.png`, fullPage: true });
const [pdf] = await Promise.all([page.waitForEvent("download"), page.click("text=Download PDF")]);
await pdf.saveAs(`${OUT}/report.pdf`);
const [md] = await Promise.all([page.waitForEvent("download"), page.click("text=Export to Notion")]);
await md.saveAs(`${OUT}/report.md`);
log("exports done");
const share = await page.request.post(`${reportUrl.replace("/audits/", "/api/audits/")}/share`);
const shareUrl = (await share.json()).url;
const anon = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const ap = await anon.newPage();
await ap.goto(shareUrl);
await ap.waitForLoadState("networkidle");
const srcs = await ap.evaluate(() => [...new Set([...document.images].map((i) => i.src))]);
const statuses = await Promise.all(srcs.map(async (s) => (await anon.request.get(s)).status()));
log("share page image statuses", statuses.join(","));

// upload flow as Pro
await page.goto(`${BASE}/audits/new`);
await page.fill("input[placeholder='Acme Analytics']", "Acme App");
await page.click("text=Continue");
await page.click("text=Upload");
await page.setInputFiles("input[type=file][multiple]", ["public/sample/app.png", "public/sample/signup.png"]);
await page.screenshot({ path: `${OUT}/10-upload.png` });
await page.click("text=Continue");
await page.click("label:has-text(\"Dashboard\")");
await page.click("text=Start Audit");
await page.waitForURL("**/processing");
await page.waitForURL(/\/audits\/c[^/]+$/, { timeout: 180000 });
await page.waitForLoadState("networkidle");
await page.screenshot({ path: `${OUT}/11-report-upload.png`, fullPage: true });
log("upload report", page.url());
// mobile view of report
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: `${OUT}/12-report-mobile.png`, fullPage: false });
await browser.close();
